/**
 * Endereços de contratos
 * Inicialmente vazios, devem ser preenchidos via variáveis de ambiente ou UI
 * Pode ser carregado de localStorage no cliente
 */
export const CONTRACT_ADDRESSES = {
  mockUSDC: (process.env.NEXT_PUBLIC_MOCK_USDC_ADDRESS || '') as `0x${string}`,
  agroChainPayments: (process.env.NEXT_PUBLIC_PAYMENTS_ADDRESS || '') as `0x${string}`,
};

/**
 * Obtém endereço do MockUSDC do localStorage ou env
 */
export function getMockUSDCAddress(): `0x${string}` {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('mockusdc_address');
    if (stored && stored.startsWith('0x')) return stored as `0x${string}`;
  }
  return CONTRACT_ADDRESSES.mockUSDC;
}

/**
 * Obtém endereço do AgroChainPayments do localStorage ou env
 */
export function getPaymentsAddress(): `0x${string}` {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('payments_address');
    if (stored && stored.startsWith('0x')) return stored as `0x${string}`;
  }
  return CONTRACT_ADDRESSES.agroChainPayments;
}

/**
 * Armazena endereços de contrato no localStorage (cliente apenas)
 */
export function setContractAddresses(mockUSDC: string, payments: string) {
  if (typeof window !== 'undefined') {
    if (mockUSDC && mockUSDC.startsWith('0x')) {
      localStorage.setItem('mockusdc_address', mockUSDC);
    }
    if (payments && payments.startsWith('0x')) {
      localStorage.setItem('payments_address', payments);
    }
  }
}
